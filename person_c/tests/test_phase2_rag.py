# SOURCE GROUNDING & EDUCATION MODE
def test_education_mode_success(education_service):
    # 13. source_class comes from actual retrieved metadata.
    # 14. The system does not invent source attribution.
    # 17. Education Mode returns a valid PersonCResponse.
    # 18. mode == "education".
    # 19. response_text is non-empty for a successful grounded query.
    # 20. The correct source_class is returned.
    # 21. Disclaimer behavior is validated according to the existing project contract.
    # 22. Education Mode does not accidentally use personalized financial-state logic.
    resp = education_service.get_guidance("What is a money map?")
    assert isinstance(resp, PersonCResponse)
    assert resp.mode == "education"
    assert resp.source_class == "RBI/SEBI/NCFE"
    assert "Based on the provided context:" in resp.response_text
    assert resp.disclaimer is True

def test_education_mode_grounding_content(education_service):
    # 15. The education response includes only knowledge supported by the retrieved context in the mocked LLM test.
    # 16. Named financial-product recommendations are not generated by the configured prompt/validation path.
    resp = education_service.get_guidance("Should I borrow a loan?")
    # Our MockLLM prepends "Based on the provided context:" to the retrieved text
    assert "A loan is borrowed money" in resp.response_text
    assert "HDFC" not in resp.response_text  # No named products

# LLM FAILURE
def test_llm_failure_handled_gracefully(retriever):
    # 23. Mock LLM failure is handled gracefully.
    failing_llm = MockLLM(simulate_failure=True)
    svc = EducationService(retriever, failing_llm)
    resp = svc.get_guidance("What is saving?")
    assert resp.response_text == "Sorry, I am currently unable to process your request."
    assert resp.source_class == "system"

def test_empty_llm_output_rejected(retriever):
    # 24. Empty LLM output cannot produce a valid successful response.
    # 25. Malformed LLM output is rejected/handled safely.
    empty_llm = MockLLM(simulate_malformed=True)
    svc = EducationService(retriever, empty_llm)
    resp = svc.get_guidance("What is saving?")
    assert resp.response_text == "Sorry, I encountered an error generating a response."
    assert resp.source_class == "system"
